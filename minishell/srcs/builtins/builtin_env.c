#include "minishell.h"

int	builtin_env(char **args, t_shell *shell)
{
	t_env	*current;

	(void) args;
	current = shell->env;
	while (current)
	{
		if (current->content)
		{
			ft_putstr_fd(current->key, STDOUT_FILENO);
			ft_putstr_fd("=", STDOUT_FILENO);
			ft_putstr_fd(current->content, STDOUT_FILENO);
			ft_putstr_fd("\n", STDOUT_FILENO);
		}
		current = current->next;
	}
	return (0);
}
