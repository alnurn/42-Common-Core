#include "minishell.h"

int	is_valid_identifier(char *str)
{
	int	i;

	if (!str || !(ft_isalpha((unsigned char) str[0]) || str[0] == '_'))
		return (0);
	i = 1;
	while (str[i] && str[i] != '=')
	{
		if (!ft_isalnum((unsigned char) str[i]) && str[i] != '_')
			return (0);
		i++;
	}
	return (1);
}
